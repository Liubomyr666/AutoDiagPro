    public static DtcRepairSuggestion Analyze(string code)
    {
        code = (code ?? "").Trim().ToUpperInvariant();
        if (Known.TryGetValue(code, out var known)) return known;

        var family = code.StartsWith("P0", StringComparison.OrdinalIgnoreCase)
            ? "Стандартный силовой OBD-II код"
            : code.StartsWith("P", StringComparison.OrdinalIgnoreCase)
                ? "Код силовой установки"
                : code.StartsWith("C", StringComparison.OrdinalIgnoreCase)
                    ? "Код шасси"
                    : code.StartsWith("B", StringComparison.OrdinalIgnoreCase)
                        ? "Код кузовной электроники"
                        : code.StartsWith("U", StringComparison.OrdinalIgnoreCase)
                            ? "Код связи между блоками"
                            : "Диагностический код";

        return new DtcRepairSuggestion(
            code,
            family + ". Для точной расшифровки нужен источник конкретной марки/ECU.",
            new[] { "Подтвердить код повторным чтением", "Проверить freeze-frame/Live Data, если доступны", "Проверить питание, массу, разъёмы и относящуюся проводку", "Сверить заводскую процедуру диагностики по VIN" },
            new[] { "Не заказывать деталь только по этому коду — сначала подтвердить неисправность" });
    }
